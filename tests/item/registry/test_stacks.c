#define COUNT(a) (sizeof(a) / sizeof((a)[0]))
static unsigned int checks;
static bool retirement_failed;
#define CHECK(condition)                                                                           \
    do {                                                                                           \
        ++checks;                                                                                  \
        if (!(condition)) {                                                                        \
            fprintf(stderr, "%s:%d: failed: %s\n", __FILE__, __LINE__, #condition);                \
            goto cleanup;                                                                          \
        }                                                                                          \
    } while (0)

/* Independent explicit constructor inputs, not a table generated by the adapter. */
static const int32_t inputs[][3] = {{0, 0, 0},
                                    {1, 1, 0},
                                    {-1, -1, -1},
                                    {INT32_MAX, INT32_MIN, INT32_MAX},
                                    {INT32_MIN, INT32_MAX, INT32_MIN},
                                    {32000, 0, -1},
                                    {-2147483647, 2, 65535},
                                    {2147483646, -64, -65536},
                                    {123456789, 64, 32768},
                                    {-987654321, 65, -32769},
                                    {256, INT32_MAX, INT32_MIN},
                                    {-42, INT32_MIN, INT32_MAX}};

typedef struct holds {
    mc_item_stack *objects[512];
    mc_item_stack_fields fields[512];
    mc_item_stack_phase phases[512];
    size_t count;
} holds;

static bool same_fields(const mc_item_stack_fields *a, const mc_item_stack_fields *b) {
    return a->id == b->id && a->count == b->count && a->damage == b->damage &&
           a->animation == b->animation;
}

static bool fields_are(const mc_item_stack *stack, int32_t id, int32_t count, int32_t damage) {
    mc_item_stack_fields fields;
    return mc_item_stack_fields_get(stack, &fields) == MC_ITEM_STACK_OK && fields.id == id &&
           fields.count == count && fields.damage == damage && fields.animation == 0;
}

static bool keep(holds *held, mc_item_stack *stack) {
    if (held->count == COUNT(held->objects))
        return false;
    for (size_t i = 0; i < held->count; ++i)
        if (held->objects[i] == stack)
            return false;
    if (mc_item_stack_retain(stack) != MC_ITEM_STACK_OK)
        return false;
    held->objects[held->count++] = stack;
    return true;
}

static bool capture(holds *held) {
    for (size_t i = 0; i < held->count; ++i)
        if (mc_item_stack_fields_get(held->objects[i], &held->fields[i]) != MC_ITEM_STACK_OK ||
            mc_item_stack_phase_get(held->objects[i], &held->phases[i]) != MC_ITEM_STACK_OK)
            return false;
    return true;
}

static bool preserved(const holds *held) {
    for (size_t i = 0; i < held->count; ++i) {
        mc_item_stack_fields fields;
        mc_item_stack_phase phase;
        if (mc_item_stack_fields_get(held->objects[i], &fields) != MC_ITEM_STACK_OK ||
            !same_fields(&fields, &held->fields[i]) ||
            mc_item_stack_phase_get(held->objects[i], &phase) != MC_ITEM_STACK_OK ||
            phase != held->phases[i])
            return false;
    }
    return true;
}

static void release_holds(holds *held) {
    for (size_t i = 0; i < held->count; ++i)
        mc_item_stack_release(held->objects[i]);
    held->count = 0;
}

static bool retire(mc_registry_classes **owner) {
    if (*owner == NULL)
        return true;
    (*owner)->entered = 0;
    if (mc_registry_classes_free(*owner, NULL) != MC_REGISTRY_OK) {
        retirement_failed = true;
        fputs("Stack fixture retirement refused; dependencies retained\n", stderr);
        return false;
    }
    *owner = NULL;
    return true;
}

/* Explicit isolated private-method admission; no class phase is made READY.
 * iz/fy has no own clinit, and numeric construction does not active-use Items. */
static mc_registry_status isolated(mc_registry_side side, mc_materials *materials,
                                   mc_java_random_profile *profile, size_t budget,
                                   mc_registry_classes **out) {
    const mc_registry_options options = {side, profile, materials, budget, NULL};
    mc_registry_status status = mc_registry_classes_allocate(&options, out, NULL);
    if (status == MC_REGISTRY_OK)
        (*out)->entered = 1;
    return status;
}

static int numeric_and_copy(mc_registry_side side, mc_materials *materials,
                            mc_java_random_profile *profile) {
    int result = 1;
    mc_registry_classes *owner = NULL;
    mc_item_stack *foreign = NULL;
    holds held = {0};
    mc_item_stack *raw_source = NULL, *raw_copy = NULL, *copy = NULL;
    mc_item_stack_phase phase;
    CHECK(isolated(side, materials, profile, 0, &owner) == MC_REGISTRY_OK);
    CHECK(owner->blocks_phase == MC_REGISTRY_COLD &&
          owner->item_states[MC_ITEM_GM_EJ].phase == MC_REGISTRY_COLD);
    for (size_t i = 0; i < COUNT(inputs); ++i) {
        mc_item_stack *stack = NULL;
        CHECK(mc_registry_stack_allocate(owner, &stack) == MC_REGISTRY_OK && keep(&held, stack));
        CHECK(fields_are(stack, 0, 0, 0));
        CHECK(mc_item_stack_phase_get(stack, &phase) == MC_ITEM_STACK_OK &&
              phase == MC_ITEM_STACK_RAW);
        CHECK(mc_registry_stack_construct_numeric(owner, stack, inputs[i][0], inputs[i][1],
                                                  inputs[i][2]) == MC_REGISTRY_OK);
        CHECK(fields_are(stack, inputs[i][0], inputs[i][1], inputs[i][2]) &&
              mc_item_stack_source(stack) == NULL);
        CHECK(mc_registry_stack_copy(owner, stack, &copy) == MC_REGISTRY_OK && keep(&held, copy));
        CHECK(copy != stack && fields_are(copy, inputs[i][0], inputs[i][1], inputs[i][2]) &&
              mc_item_stack_source(copy) == NULL);
        const mc_item_stack *newest = NULL;
        CHECK(mc_registry_stack_get(owner, 0, &newest) == MC_REGISTRY_OK && newest == copy);
    }

    CHECK(mc_registry_stack_allocate(owner, &raw_source) == MC_REGISTRY_OK &&
          keep(&held, raw_source));
    CHECK(mc_registry_stack_copy(owner, raw_source, &raw_copy) == MC_REGISTRY_OK &&
          keep(&held, raw_copy));
    CHECK(fields_are(raw_copy, 0, 0, 0) && raw_copy != raw_source);
    CHECK(mc_item_stack_phase_get(raw_source, &phase) == MC_ITEM_STACK_OK &&
          phase == MC_ITEM_STACK_RAW);
    CHECK(mc_item_stack_phase_get(raw_copy, &phase) == MC_ITEM_STACK_OK &&
          phase == MC_ITEM_STACK_READY);

    /* Actual deep provenance on a live class-held source; clone must not keep it. */
    const uint16_t payload_name[] = {'p'};
    const uint8_t bytes[] = {0, 0x80, 0xff};
    mc_nbt_tag payload = {.type = MC_NBT_BYTE_ARRAY,
                          .name = {payload_name, 1},
                          .value.byte_array = {bytes, COUNT(bytes)}};
    const mc_nbt_tag *children[] = {&payload};
    mc_nbt_tag compound = {.type = MC_NBT_COMPOUND, .value.compound = {children, 1}};
    mc_item_stack_error error;
    CHECK(mc_item_stack_preserve_source(held.objects[0], &compound, NULL, &error) ==
          MC_ITEM_STACK_OK);
    const mc_nbt_tag *source = mc_item_stack_source(held.objects[0]);
    CHECK(source != NULL && source != &compound);
    CHECK(mc_registry_stack_copy(owner, held.objects[0], &copy) == MC_REGISTRY_OK &&
          keep(&held, copy));
    CHECK(fields_are(copy, 0, 0, 0) && mc_item_stack_source(copy) == NULL &&
          mc_item_stack_source(held.objects[0]) == source);
    CHECK(mc_item_stack_count_set(copy, -75) == MC_ITEM_STACK_OK &&
          mc_item_stack_damage_set(copy, 123456) == MC_ITEM_STACK_OK);
    CHECK(fields_are(held.objects[0], 0, 0, 0) && fields_are(copy, 0, -75, 123456));

    CHECK(mc_item_stack_allocate(&foreign) == MC_ITEM_STACK_OK);
    mc_item_stack *sentinel = held.objects[0];
    size_t count = mc_registry_stack_count(owner), allocated = owner->allocation_bytes;
    CHECK(mc_registry_stack_allocate(NULL, &sentinel) == MC_REGISTRY_INVALID_ARGUMENT &&
          sentinel == held.objects[0]);
    CHECK(mc_registry_stack_allocate(owner, NULL) == MC_REGISTRY_INVALID_ARGUMENT);
    CHECK(mc_registry_stack_construct_numeric(NULL, raw_source, 1, 2, 3) ==
          MC_REGISTRY_INVALID_ARGUMENT);
    CHECK(mc_registry_stack_construct_numeric(owner, NULL, 1, 2, 3) ==
          MC_REGISTRY_INVALID_ARGUMENT);
    CHECK(mc_registry_stack_construct_numeric(owner, foreign, 1, 2, 3) ==
          MC_REGISTRY_INVALID_ARGUMENT);
    CHECK(mc_registry_stack_construct_numeric(owner, copy, 1, 2, 3) ==
              MC_REGISTRY_INVALID_ARGUMENT &&
          fields_are(copy, 0, -75, 123456));
    CHECK(mc_registry_stack_construct_item_values(owner, foreign, NULL, 2, 3) ==
          MC_REGISTRY_INVALID_ARGUMENT);
    CHECK(mc_registry_stack_construct_block_values(owner, foreign, NULL, 2, 3) ==
          MC_REGISTRY_INVALID_ARGUMENT);
    CHECK(mc_registry_stack_construct_item_values(NULL, raw_source, NULL, 2, 3) ==
          MC_REGISTRY_INVALID_ARGUMENT);
    CHECK(mc_registry_stack_construct_block_values(NULL, raw_source, NULL, 2, 3) ==
          MC_REGISTRY_INVALID_ARGUMENT);
    CHECK(mc_registry_stack_construct_item_values(owner, copy, NULL, 2, 3) ==
              MC_REGISTRY_INVALID_ARGUMENT &&
          fields_are(copy, 0, -75, 123456));
    CHECK(mc_registry_stack_construct_block_values(owner, copy, NULL, 2, 3) ==
              MC_REGISTRY_INVALID_ARGUMENT &&
          fields_are(copy, 0, -75, 123456));
    CHECK(mc_registry_stack_copy(owner, NULL, &sentinel) == MC_REGISTRY_INVALID_ARGUMENT &&
          sentinel == held.objects[0]);
    CHECK(mc_registry_stack_copy(NULL, raw_source, &sentinel) == MC_REGISTRY_INVALID_ARGUMENT &&
          sentinel == held.objects[0]);
    CHECK(mc_registry_stack_copy(owner, raw_source, NULL) == MC_REGISTRY_INVALID_ARGUMENT);
    owner->entered = 0;
    CHECK(mc_registry_stack_allocate(owner, &sentinel) == MC_REGISTRY_INVALID_ARGUMENT &&
          sentinel == held.objects[0]);
    CHECK(mc_registry_stack_construct_numeric(owner, raw_source, 1, 2, 3) ==
              MC_REGISTRY_INVALID_ARGUMENT &&
          fields_are(raw_source, 0, 0, 0));
    CHECK(mc_registry_stack_construct_item_values(owner, raw_source, NULL, 2, 3) ==
          MC_REGISTRY_INVALID_ARGUMENT);
    CHECK(mc_registry_stack_construct_block_values(owner, raw_source, NULL, 2, 3) ==
          MC_REGISTRY_INVALID_ARGUMENT);
    CHECK(mc_registry_stack_copy(owner, raw_source, &sentinel) == MC_REGISTRY_INVALID_ARGUMENT &&
          sentinel == held.objects[0]);
    owner->entered = 1;
    CHECK(mc_registry_stack_count(owner) == count && owner->allocation_bytes == allocated);
    CHECK(fields_are(foreign, 0, 0, 0) && mc_registry_stack_count(owner) == held.count);
    CHECK(owner->blocks_phase == MC_REGISTRY_COLD &&
          owner->item_states[MC_ITEM_GM_EJ].phase == MC_REGISTRY_COLD);
    CHECK(capture(&held));
    CHECK(retire(&owner));
    CHECK(preserved(&held));
    CHECK(mc_item_stack_source(held.objects[0]) == source && mc_item_stack_source(copy) == NULL);
    result = 0;
cleanup:
    if (!retire(&owner))
        result = 1;
    release_holds(&held);
    mc_item_stack_release(foreign);
    return result;
}

static int actual_object_values(mc_registry_side side, mc_materials *materials,
                                mc_java_random_profile *profile) {
    int result = 1;
    mc_registry_classes *owner = NULL;
    holds held = {0};
    const mc_item *item = NULL;
    const mc_block *block = NULL;
    const mc_registry_options options = {side, profile, materials, 0, NULL};
    CHECK(mc_registry_classes_allocate(&options, &owner, NULL) == MC_REGISTRY_OK);
    /* Real initialization reaches its genuine absent-resource failure. Inspect
     * its actual published objects; never make failed classes READY. */
    CHECK(mc_registry_classes_initialize_blocks(owner, NULL) ==
          MC_REGISTRY_UNIMPLEMENTED_DEPENDENCY);
    CHECK(mc_registry_classes_inspect_item_static(owner, "d", &item, NULL) == MC_REGISTRY_OK &&
          item != NULL);
    CHECK(mc_registry_classes_inspect_block_static(owner, "u", &block, NULL) == MC_REGISTRY_OK &&
          block != NULL);
    const mc_item_fields *item_fields = mc_item_fields_get(item);
    const mc_block_fields *block_fields = mc_block_fields_get(block);
    CHECK(item_fields != NULL && block_fields != NULL);
    mc_registry_phase block_phase = owner->blocks_phase;
    mc_registry_phase item_phase = owner->item_states[MC_ITEM_GM_EJ].phase;
    owner->entered = 1; /* Isolated adapter method, not another Java active use. */
    for (size_t i = 0; i < 4; ++i) {
        mc_item_stack *raw = NULL;
        CHECK(mc_registry_stack_allocate(owner, &raw) == MC_REGISTRY_OK && keep(&held, raw));
        mc_registry_status status;
        int32_t id, count, damage;
        if (i == 0) {
            status =
                mc_registry_stack_construct_item_values(owner, raw, item, INT32_MIN, INT32_MAX);
            id = item_fields->bf;
            count = INT32_MIN;
            damage = INT32_MAX;
        } else if (i == 1) {
            status = mc_registry_stack_construct_block_values(owner, raw, block, -4, -1);
            id = block_fields->bn;
            count = -4;
            damage = -1;
        } else if (i == 2) {
            status = mc_registry_stack_construct_item(owner, raw, item);
            id = item_fields->bf;
            count = 1;
            damage = 0;
        } else {
            status = mc_registry_stack_construct_block(owner, raw, block);
            id = block_fields->bn;
            count = 1;
            damage = 0;
        }
        CHECK(status == MC_REGISTRY_OK && fields_are(raw, id, count, damage));
    }
    for (size_t i = 0; i < 2; ++i) {
        mc_item_stack *raw = NULL;
        mc_item_stack_phase phase;
        CHECK(mc_registry_stack_allocate(owner, &raw) == MC_REGISTRY_OK && keep(&held, raw));
        size_t count = mc_registry_stack_count(owner), bytes = owner->allocation_bytes;
        CHECK((i == 0 ? mc_registry_stack_construct_item_values(owner, raw, NULL, -9, 17)
                      : mc_registry_stack_construct_block_values(owner, raw, NULL, -9, 17)) ==
              MC_REGISTRY_NULL_REFERENCE);
        CHECK(mc_registry_stack_count(owner) == count && owner->allocation_bytes == bytes &&
              fields_are(raw, 0, 0, 0));
        CHECK(mc_item_stack_phase_get(raw, &phase) == MC_ITEM_STACK_OK &&
              phase == MC_ITEM_STACK_RAW);
        CHECK(owner->last_error.constructor_class != NULL &&
              strcmp(owner->last_error.constructor_class,
                     side == MC_REGISTRY_CLIENT ? "iz" : "fy") == 0 &&
              owner->last_error.constructor_pc == 2);
    }
    CHECK(owner->blocks_phase == block_phase &&
          owner->item_states[MC_ITEM_GM_EJ].phase == item_phase);
    CHECK(capture(&held));
    CHECK(retire(&owner));
    CHECK(preserved(&held));
    result = 0;
cleanup:
    if (!retire(&owner))
        result = 1;
    release_holds(&held);
    return result;
}

static int natural_limit(mc_registry_side side, mc_materials *materials,
                         mc_java_random_profile *profile) {
    int result = 1;
    mc_registry_classes *owner = NULL;
    holds held = {0};
    const size_t budget = sizeof(mc_registry_classes) + 4096;
    CHECK(isolated(side, materials, profile, budget, &owner) == MC_REGISTRY_OK);
    bool exhausted = false;
    for (size_t i = 0; i < COUNT(held.objects); ++i) {
        mc_item_stack *sentinel = held.count == 0 ? NULL : held.objects[0];
        mc_item_stack *raw = sentinel;
        size_t before = mc_registry_stack_count(owner);
        mc_registry_status status = mc_registry_stack_allocate(owner, &raw);
        if (status == MC_REGISTRY_LIMIT) {
            CHECK(raw == sentinel && mc_registry_stack_count(owner) == before &&
                  owner->last_error.status == MC_REGISTRY_LIMIT);
            exhausted = true;
            break;
        }
        CHECK(status == MC_REGISTRY_OK && keep(&held, raw));
        CHECK(mc_registry_stack_construct_numeric(owner, raw, (int32_t)i, -7, INT32_MIN) ==
              MC_REGISTRY_OK);
    }
    CHECK(exhausted && held.count != 0 && owner->allocation_bytes <= budget);
    CHECK(capture(&held));
    size_t count = mc_registry_stack_count(owner);
    mc_item_stack *out = held.objects[0];
    CHECK(mc_registry_stack_copy(owner, held.objects[0], &out) == MC_REGISTRY_LIMIT &&
          out == held.objects[0]);
    CHECK(owner->last_error.status == MC_REGISTRY_LIMIT &&
          mc_registry_stack_count(owner) == count && owner->allocation_bytes <= budget &&
          preserved(&held));
    CHECK(retire(&owner));
    CHECK(preserved(&held));
    result = 0;
cleanup:
    if (!retire(&owner))
        result = 1;
    release_holds(&held);
    return result;
}

int main(void) {
    int result = 1;
    mc_materials *materials = NULL;
    mc_java_random_profile *profile = NULL;
    CHECK(mc_materials_create(&materials));
    CHECK(mc_java_random_profile_create(SIZE_MAX, &profile) == MC_JAVA_RANDOM_PROFILE_OK);
    for (int side = MC_REGISTRY_CLIENT; side <= MC_REGISTRY_SERVER; ++side) {
        CHECK(numeric_and_copy((mc_registry_side)side, materials, profile) == 0);
        CHECK(actual_object_values((mc_registry_side)side, materials, profile) == 0);
        CHECK(natural_limit((mc_registry_side)side, materials, profile) == 0);
    }
    result = 0;
cleanup:
    if (!retirement_failed) {
        mc_java_random_profile_free(profile);
        mc_materials_destroy(materials);
    }
    if (result == 0 && printf("Registry Stack adapters: %u checks passed\n", checks) < 0)
        result = 1;
    return result;
}
