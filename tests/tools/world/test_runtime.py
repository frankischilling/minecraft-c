#!/usr/bin/env python3
"""Run native runtime/owner contracts on fresh, retained owned worlds."""

import argparse
import importlib.util
import json
from pathlib import Path
import struct
import sys
import time

ROOT = Path(__file__).resolve().parents[3]
SPEC = importlib.util.spec_from_file_location("int_set_capture", ROOT / "scripts/reference/java/compare_int_set.py")
CAPTURE = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(CAPTURE)
SCENARIOS = ("ownership-and-runtime", "generation", "generation-copy-limit", "profile-and-entity-bindings",
             "world-info-bindings", "saved-data-ids", "typed-world-info", "game-world", "world-registry",
             "world-biome-runtime", "world-lighting-runtime", "world-light-queue-runtime",
             "world-chunk-objects", "world-provider-generation", "world-provider-activation")


def provider_fixture(root):
    """Compare observed inputs/data with the retained original seed23 case.

    This concrete GAME call has an empty cache. Only the context-independent
    voxel arrays are compared; the original cached baseline's queue/height
    query trace and constructor route are not supplied as native observations.
    """
    helper = ROOT / "tests/tools/generation/test_normal_interop.py"
    spec = importlib.util.spec_from_file_location("provider_original_fixture", helper)
    normal = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(normal)
    fixture = normal.strict_json(normal.FIXTURE.read_bytes())
    normal.validate_fixture(fixture)
    case = next(row for row in fixture["cases"] if row["seed"] == 23)
    expected = normal.strict_json(normal.unpack(case["expected"]))
    normal.validate_projection(expected, 23)
    first = expected["calls"][0]
    CAPTURE.require(first["coordinates"] == [1, 0], "original provider coordinate")
    observed_registry = (root / "provider-generation-registry.bin").read_bytes()
    observed_climate = (root / "provider-generation-climate.bin").read_bytes()
    CAPTURE.require(len(observed_registry) == 1050 and len(observed_climate) == 6144,
                    "complete observed Registry/climate input artifacts")
    for side in ("client", "server"):
        raw = normal.unpack(case["sides"][side]["input"])
        normal.validate_input(raw, 23)
        header = struct.Struct(">4sqBiIIII")
        _, seed, no_sky, _, _, _, _, _ = header.unpack_from(raw)
        CAPTURE.require(seed == 23 and no_sky == 0, "original seed/no-sky input")
        offset = header.size
        CAPTURE.require(raw[offset:offset + 1050] == observed_registry,
                        side + " actual opacity and Biome p/q equal original input")
        offset += 1050
        climate = bytearray()
        for _ in range(3):
            length, = struct.unpack_from(">i", raw, offset)
            CAPTURE.require(length == 256, "original full climate input extent")
            offset += 4
            climate.extend(raw[offset:offset + length * 8])
            offset += length * 8
        CAPTURE.require(bytes(climate) == observed_climate,
                        side + " actual warmed climate equals original input")
        CAPTURE.require(struct.unpack_from(">i", raw, offset)[0] == -1,
                        "original cached manager d is null")
    data = first["data"]
    lengths = {"blocks": 32768, "metadata": 16384, "skylight": 16384,
               "block_light": 16384, "heightmap": 256}
    observed = (root / "provider-generation-first.bin").read_bytes()
    CAPTURE.require(len(observed) == sum(lengths.values()), "complete generated data artifact")
    offset = 0
    for name, length in lengths.items():
        CAPTURE.require(data[name]["length"] == length, "original array extent: " + name)
        array = bytes.fromhex(data[name]["values"])
        CAPTURE.require(len(array) == length and observed[offset:offset + length] == array,
                        "all actual generated bytes equal original: " + name)
        offset += length
    return {"scope": "one concrete GAME provider call against retained original client/server data",
            "seed": 23, "coordinates": [1, 0], "compared_data_bytes": len(observed),
            "registry_input_bytes": len(observed_registry), "climate_input_bytes": len(observed_climate),
            "cache_baseline_equal": False, "height_query_trace_compared": False,
            "fresh_original_execution": False}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--executable", required=True, type=Path)
    parser.add_argument("--work-dir", required=True, type=Path)
    parser.add_argument("--scenario", choices=SCENARIOS, required=True)
    args = parser.parse_args()
    work = None
    report = {"schema": 1, "scope": "constructed native runtime/owner contracts", "tested_commit": None,
              "scenario": args.scenario, "passed": False, "processes": []}
    try:
        CAPTURE.require(args.executable.is_file(), "native contract executable is missing")
        work = CAPTURE.capture_root(args.work_dir, [sys.executable])
        paths = {"executable": args.executable.resolve(), "driver": Path(__file__),
                 "capture_support": Path(SPEC.origin), "test": ROOT / "tests/world/runtime/test_runtime.c",
                 "runtime": ROOT / "src/world/runtime/runtime.c", "runtime_header": ROOT / "include/mc/world/runtime/runtime.h",
                 "entity": ROOT / "src/entity/entity.c", "entity_header": ROOT / "include/mc/entity/entity.h",
                 "entity_internal": ROOT / "src/entity/entity_internal.h",
                 "store": ROOT / "src/world/storage/store.c", "store_header": ROOT / "include/mc/world/storage/store.h",
                 "binding_test": ROOT / "tests/world/runtime/test_info_binding.c",
                 "info": ROOT / "src/world/info/info.c", "info_header": ROOT / "include/mc/world/info/info.h",
                 "level": ROOT / "src/storage/level/level.c", "level_header": ROOT / "include/mc/storage/level/level.h",
                 "saved_data_test": ROOT / "tests/world/saved_data/test_storage.c",
                 "saved_data": ROOT / "src/world/saved_data/storage.c",
                 "saved_data_header": ROOT / "include/mc/world/saved_data/storage.h",
                 "files": ROOT / "src/world/storage/files.c", "files_header": ROOT / "src/world/storage/files.h",
                 "typed_info_test": ROOT / "tests/world/storage/test_typed_info.c",
                 "construction": ROOT / "src/world/runtime/construction.c",
                 "construction_header": ROOT / "include/mc/world/runtime/construction.h",
                 "construction_internal": ROOT / "src/world/runtime/construction_internal.h",
                 "world_height": ROOT / "src/world/runtime/height.c",
                 "world_lighting": ROOT / "src/world/runtime/lighting.c",
                 "world_lighting_header": ROOT / "include/mc/world/runtime/lighting.h",
                 "world_lighting_internal": ROOT / "src/world/runtime/lighting_internal.h",
                 "chunk_object": ROOT / "src/world/chunk/object.c",
                 "chunk_object_header": ROOT / "include/mc/world/chunk/object.h",
                 "chunk_object_internal": ROOT / "src/world/chunk/object_internal.h",
                 "chunk_runtime": ROOT / "src/world/runtime/chunks.c",
                 "chunk_runtime_header": ROOT / "include/mc/world/runtime/chunks.h",
                 "chunk_serializer": ROOT / "src/world/storage/chunk.c",
                 "chunk_build_internal": ROOT / "src/world/storage/chunk_build_internal.h",
                 "generated_internal": ROOT / "src/world/storage/generated_internal.h",
                 "stored_objects_internal": ROOT / "src/world/storage/objects_internal.h",
                 "chunk_activation": ROOT / "src/world/runtime/activation.c",
                 "chunk_activation_internal": ROOT / "src/world/runtime/activation_internal.h",
                 "registry_runtime": ROOT / "src/block/registry/runtime.c",
                 "registry_runtime_internal": ROOT / "src/block/registry/runtime_internal.h",
                 "stdout": ROOT / "src/platform/text/stdout.c",
                 "stdout_header": ROOT / "src/platform/text/stdout.h",
                 "runtime_internal": ROOT / "src/world/runtime/runtime_internal.h",
                 "dimension": ROOT / "src/world/dimension/dimension.c",
                 "dimension_header": ROOT / "include/mc/world/dimension/dimension.h",
                 "biome": ROOT / "src/world/biome/biome.c",
                 "biome_internal": ROOT / "src/world/biome/biome_internal.h",
                 "provider": ROOT / "src/world/runtime/provider.c",
                 "provider_internal": ROOT / "src/world/runtime/provider_internal.h",
                 "environment": ROOT / "src/world/runtime/environment.c",
                 "environment_header": ROOT / "include/mc/world/runtime/environment.h",
                 "blocks": ROOT / "src/world/runtime/blocks.c",
                 "blocks_header": ROOT / "include/mc/world/runtime/blocks.h"}
        if args.scenario == "game-world":
            paths["game_test"] = ROOT / "tests/world/runtime/test_game_world.c"
        if args.scenario == "world-registry":
            paths.update({
                "registry_test": ROOT / "tests/world/runtime/test_world_registry.c",
                "registry_runtime": ROOT / "src/block/registry/runtime.c",
                "registry_runtime_header": ROOT / "include/mc/block/registry/runtime.h",
                "registry": ROOT / "src/block/registry/registry.c",
                "registry_internal": ROOT / "src/block/registry/registry_internal.h",
                "world_registry": ROOT / "src/world/runtime/registry.c",
            })
        if args.scenario == "world-biome-runtime":
            paths.update({
                "biome_runtime_test": ROOT / "tests/world/dimension/test_biome_runtime.c",
                "biome_runtime_header": ROOT / "include/mc/world/dimension/biome_runtime.h",
                "biome_sampling": ROOT / "src/world/biome/sampling.c",
                "biome_sampling_header": ROOT / "include/mc/world/biome/sampling.h",
                "biome_sampling_internal": ROOT / "src/world/biome/sampling_internal.h",
                "fixed_sampling": ROOT / "src/world/biome/fixed_sampling.c",
                "biome_registry": ROOT / "src/world/biome/registry.c",
                "biome_registry_header": ROOT / "include/mc/world/biome/registry.h",
                "biome_registry_internal": ROOT / "src/world/biome/registry_internal.h",
                "registry_runtime": ROOT / "src/block/registry/runtime.c",
                "registry_runtime_header": ROOT / "include/mc/block/registry/runtime.h",
                "registry_runtime_internal": ROOT / "src/block/registry/runtime_internal.h",
                "registry_internal": ROOT / "src/block/registry/registry_internal.h",
                "world_registry": ROOT / "src/world/runtime/registry.c",
            })
        if args.scenario in ("world-lighting-runtime", "world-light-queue-runtime"):
            paths["lighting_test"] = ROOT / ("tests/world/runtime/test_lighting_runtime.c"
                if args.scenario == "world-lighting-runtime" else "tests/world/runtime/test_light_queue_runtime.c")
        if args.scenario == "world-chunk-objects":
            paths["chunk_object_test"] = ROOT / "tests/world/runtime/test_chunk_objects.c"
        if args.scenario in ("world-provider-generation", "world-provider-activation"):
            for name in ("generation", "surface", "caves", "generation_internal"):
                paths["provider_" + name] = ROOT / ("src/world/runtime/generation/" + name +
                    (".h" if name.endswith("_internal") else ".c"))
            for name in ("terrain", "surface", "caves"):
                paths["terrain_" + name] = ROOT / ("src/world/terrain/" + name + ".c")
                paths["terrain_" + name + "_header"] = ROOT / ("src/world/terrain/" + name + "_internal.h")
            paths.update({
                "provider_state": ROOT / "src/world/runtime/provider_state_internal.h",
                "provider_test": ROOT / ("tests/world/runtime/test_provider_generation.c"
                    if args.scenario == "world-provider-generation" else
                    "tests/world/runtime/test_provider_activation.c"),
                "normal_fixture": ROOT / "tests/reference/generation/normal_fixtures.json",
                "normal_fixture_helper": ROOT / "tests/tools/generation/test_normal_interop.py"})
        report["inputs"] = {name: CAPTURE.file_fingerprint(path) for name, path in paths.items()}
        for name, path in paths.items():
            if name != "executable":
                (work / (name + path.suffix)).write_bytes(path.read_bytes())
        root = work / "world-\u00e9-\u4e16\u754c"
        CAPTURE.require(not root.exists() and not root.is_symlink(), "world root must be fresh")
        command = [str(args.executable.resolve()), args.scenario, str(root).encode("utf-8").hex()]
        clock_before = int(time.time())
        stdout, stderr = CAPTURE.run(command, work=work, name="native", records=report["processes"],
                                     deadline=time.monotonic() + 70)
        clock_after = int(time.time())
        CAPTURE.require(not stderr, "native contract stderr must be empty")
        text = stdout.decode("ascii").replace("\r\n", "\n")
        if args.scenario in ("world-registry", "world-biome-runtime", "world-lighting-runtime",
                             "world-light-queue-runtime", "world-chunk-objects", "world-provider-generation",
                             "world-provider-activation"):
            lines = text.splitlines(keepends=True)
            CAPTURE.require(bool(lines), "native registry contract result is missing")
            console = ("16 achievements\n", "151 recipes\n")
            if args.scenario == "world-light-queue-runtime":
                console += ("More than 1000000 updates, aborting lighting updates\n",)
            CAPTURE.require(all(line in console for line in lines[:-1]),
                            "unexpected native bootstrap console output")
            report["bootstrap_console"] = lines[:-1]
            if args.scenario == "world-lighting-runtime":
                CAPTURE.require(not lines[:-1], "height queries must not print bootstrap or queue diagnostics")
            elif args.scenario == "world-light-queue-runtime":
                CAPTURE.require(lines[:-1] == ["16 achievements\n", "151 recipes\n",
                    "More than 1000000 updates, aborting lighting updates\n"],
                    "complete ordered queue bootstrap and overflow diagnostics")
            elif args.scenario == "world-chunk-objects":
                CAPTURE.require(lines[:-1] == ["16 achievements\n", "151 recipes\n"],
                                "complete ordered Chunk opacity bootstrap diagnostics")
            elif args.scenario == "world-provider-generation":
                CAPTURE.require(lines[:-1] == ["16 achievements\n", "151 recipes\n"] * 2,
                                "complete two-owner generation bootstrap diagnostics")
            elif args.scenario == "world-provider-activation":
                CAPTURE.require(lines[:-1] == ["16 achievements\n", "151 recipes\n"],
                                "complete one-owner acquisition bootstrap diagnostics")
            text = lines[-1]
        CAPTURE.require(text.startswith("PASS: ") and text.endswith("(" + args.scenario + ")\n") and
                        text.count("\n") == 1, "complete native contract result")
        if args.scenario == "world-provider-generation":
            report["provider_fixture"] = provider_fixture(root)
        for name, path in paths.items():
            CAPTURE.require(CAPTURE.file_fingerprint(path) == report["inputs"][name], "input changed: " + name)
        report["inputs_unchanged"] = True
        report["world_files"] = {path.relative_to(root).as_posix(): CAPTURE.file_fingerprint(path)
                                 for path in sorted(root.rglob("*")) if path.is_file()}
        timestamps = []
        for path in sorted(root.rglob("*.mcr")):
            with path.open("rb") as stream:
                header = stream.read(8192)
            CAPTURE.require(len(header) == 8192, "complete region header")
            for slot in range(1024):
                if struct.unpack_from(">I", header, slot * 4)[0] != 0:
                    timestamp = struct.unpack_from(">I", header, 4096 + slot * 4)[0]
                    if args.scenario == "world-provider-activation":
                        opaque_input = path.relative_to(root).as_posix() == "loaded/region/r.1.0.mcr"
                        if opaque_input:
                            CAPTURE.require(slot in (136, 137) and timestamp == 1,
                                            "untouched opaque input fixture timestamp")
                        else:
                            CAPTURE.require(clock_before <= timestamp <= clock_after,
                                            "actual GAME region wall clock in execution window")
                    else:
                        expected_timestamp = 1 if args.scenario in ("world-lighting-runtime", "world-chunk-objects") else 0xfedcba98
                        CAPTURE.require(timestamp == expected_timestamp, "explicit native region clock in live header cell")
                    timestamps.append({"file": path.relative_to(root).as_posix(), "slot": slot, "timestamp": timestamp})
        CAPTURE.require(bool(timestamps) == (args.scenario in ("ownership-and-runtime", "generation", "world-info-bindings", "world-lighting-runtime", "world-chunk-objects", "world-provider-activation")),
                        "expected committed region slots")
        report["region_timestamps_checked"] = timestamps
        if args.scenario == "world-provider-activation":
            report["actual_game_clock_window"] = [clock_before, clock_after]
        report["passed"] = True
        print(text, end="")
        return 0
    except (CAPTURE.Failure, OSError, ValueError) as error:
        report["failure"] = str(error)
        print("FAIL: " + str(error), file=sys.stderr)
        return 1
    finally:
        if work is not None:
            (work / "report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8", newline="\n")
            print("Capture: " + str(work))


if __name__ == "__main__":
    sys.exit(main())
