"""Render portable C data from declarations and unchanged-original observations."""
import json
import re


def tokens(source):
    """Compare generated C data independently of the repository's formatter."""
    return [word for word in re.findall(
        r'/\*[\s\S]*?\*/|//[^\n]*|"(?:\\.|[^"\\])*"|[A-Za-z_]\w*|-?\d+|[^\s]', source)
        if not word.startswith(('/*', '//'))]


def number(value):
    return 'INT32_MIN' if value == -2147483648 else str(value)


def cell(label, snapshot):
    if label is None:
        return '{0}'
    stack = snapshot['stacks'][label]
    return '{' + json.dumps(label) + ', ' + ', '.join(number(stack[key]) for key in
        ('id', 'count', 'damage', 'animation')) + '}'


def cells(values, snapshot):
    entries = [f'[{index}] = {cell(label, snapshot)}' for index, label in enumerate(values)
               if label is not None]
    return '{' + ', '.join(entries) + '}' if entries else '{{0}}'


def header(cases, observations):
    observed = {row['profile']: row for row in observations}
    layouts = [case for case in cases if case['target'] == 'cd' and
               case['operation'] == 'construct' and not case['player_null'] and
               case['left'] is not None and case['right'] is not None]
    shifts = [case for case in cases if case['target'] == 'cd' and
              case['operation'] == 'shift' and case['native_candidate']]
    out = ['/* Generated by projection.py from declared inputs and untouched-original rows.',
           ' * Scope: controlled LW leaves; no actual Player/Chest/NBT or GUI qualification. */',
           '#ifndef MC_REFERENCE_CHEST_CONTAINER_NATIVE_OBSERVATIONS_H',
           '#define MC_REFERENCE_CHEST_CONTAINER_NATIVE_OBSERVATIONS_H',
           '#include <stdbool.h>', '#include <stddef.h>', '#include <stdint.h>', '',
           'typedef struct mc_chest_stack_reference {',
           '    const char *identity; /* NULL means absent; shared labels mean the same object. */',
           '    int32_t id, count, damage, animation;',
           '} mc_chest_stack_reference;', '',
           'typedef struct mc_chest_layout_reference {',
           '    const char *profile;', '    int32_t size, rows;', '    size_t slot_count;',
           '    /* Container index, inventory kind (1=Player input,2=Chest input), index,x,y. */',
           '    int32_t slots[90][5];',
           '} mc_chest_layout_reference;', '',
           'static const mc_chest_layout_reference mc_chest_layout_references[] = {']
    for case in layouts:
        row = observed[case['profile']]
        if row['error'] is not None or row['rows'] is None or len(row['layout']) > 90:
            raise ValueError('complete bounded original layout')
        out.append('    {' + json.dumps(case['profile']) + ', ' +
                   number(case['right']['sizes'][0]) + ', ' + number(row['rows']) + ', ' +
                   str(len(row['layout'])) + ', {')
        for index, owner, inventory_index, x, y in row['layout']:
            if owner not in ('L', 'R'):
                raise ValueError('declared nonnull LW input')
            out.append('        {' + ', '.join(map(number, (index, 1 if owner == 'L' else 2,
                                                       inventory_index, x, y))) + '},')
        out.append('    }},')
    out += ['};', '', 'typedef struct mc_chest_shift_reference {',
            '    const char *profile;', '    int32_t storage_size, source_slot;',
            '    size_t input_stack_count, tracked_stack_count;',
            '    mc_chest_stack_reference input_stacks[2], tracked_stacks[4];',
            '    mc_chest_stack_reference before_main[36], before_storage[54];',
            '    mc_chest_stack_reference after_main[36], after_storage[54], result;',
            '} mc_chest_shift_reference;', '',
            'static const mc_chest_shift_reference mc_chest_shift_references[] = {']
    for case in shifts:
        row = observed[case['profile']]
        before, after = row['before'], row['after']
        if (row['error'] is not None or len(before['stacks']) > 2 or len(after['stacks']) > 4 or
                len(case['right']['sizes']) != 1 or case['right']['sizes'][0] not in (27, 54)):
            raise ValueError('supported declared Shift projection')
        size = case['right']['sizes'][0]
        out.append('    {')
        out.append('        ' + json.dumps(case['profile']) + ', ' + number(size) + ', ' +
                   number(case['index']) + ', ' + str(len(before['stacks'])) + ', ' +
                   str(len(after['stacks'])) + ',')
        for snapshot in (before, after):
            entries = ', '.join(cell(label, snapshot) for label in snapshot['stacks'])
            out.append('        {' + (entries or '{0}') + '},')
        for snapshot, owner, count in ((before, 'left', 36), (before, 'right', size),
                                       (after, 'left', 36), (after, 'right', size)):
            if snapshot[owner] is None or any(label is not None for label in snapshot[owner][count:]):
                raise ValueError('unobserved controlled tail must be empty')
            out.append('        ' + cells(snapshot[owner][:count], snapshot) + ',')
        out.append('        ' + cell(row['result'], after))
        out.append('    },')
    out += ['};', '', '#endif', '']
    return '\n'.join(out)
